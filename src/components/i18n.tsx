export type TranslationKey = keyof typeof EN;
export type Translator = (key: TranslationKey, values?: Record<string, string | number>) => string;

const LanguageContext = createContext<{ lang: Language; setLanguage: (lang: Language) => void } | null>(null);

export function LanguageProvider({ initialLanguage, children }: { initialLanguage: Language; children: React.ReactNode }) {
  const [lang, setLang] = useState<Language>(initialLanguage);
  const setLanguage = (next: Language) => {
    setLang(next);
    document.documentElement.lang = next;
    document.cookie = `${LANGUAGE_COOKIE}=${next}; Path=/; Max-Age=31536000; SameSite=Lax`;
  };
  return <LanguageContext.Provider value={{ lang, setLanguage }}>{children}</LanguageContext.Provider>;
}

export function useT() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error('useT must be used inside LanguageProvider');
  const { lang, setLanguage } = context;
  const dictionary = lang === 'vi' ? VI : EN;
  const t = useMemo<Translator>(() => (key, values) => {
    let result = dictionary[key];
    for (const [name, value] of Object.entries(values ?? {})) result = result.replaceAll(`{${name}}`, String(value));
    return result;
  }, [dictionary]);
  const locale = LOCALES[lang];
  const number = (value: number, options?: Intl.NumberFormatOptions) => new Intl.NumberFormat(locale, options).format(value);
  const date = (value: string | number | Date, options?: Intl.DateTimeFormatOptions) => new Intl.DateTimeFormat(locale, options ?? { dateStyle: 'medium' }).format(new Date(value));
  const time = (value: string | number | Date) => new Intl.DateTimeFormat(locale, { hour: '2-digit', minute: '2-digit' }).format(new Date(value));
  const age = (value: string, detailed = false) => {
    const minutes = Math.max(0, (Date.now() - new Date(value).getTime()) / 60_000);
    if (!Number.isFinite(minutes) || minutes < 1) return t('justNow');
    if (minutes < 60) return t('minutesAgo', { count: Math.floor(minutes) });
    const hours = minutes / 60;
    if (hours < 24) return t('hoursAgo', { count: Math.floor(hours) });
    const days = Math.floor(hours / 24);
    return detailed ? t('daysHoursAgo', { days, hours: Math.floor(hours % 24) }) : t('daysAgo', { count: days });
  };
  return { lang, locale, setLanguage, t, number, date, time, age };
}

export function translateApiError(error: unknown, t: Translator, fallback: TranslationKey = 'apiError') {
  if (!(error instanceof ApiError)) return t(fallback);
  const known: Partial<Record<string, TranslationKey>> = {
    sign_in_required: 'signInFirst',
    sign_in_failed: 'signInNotCompleted',
    pool_too_small: 'onlyCoins',
    no_pool: 'caseFilling',
    rate_limited: 'rateLimited',
    empty: 'noSponsoredDrops',
    needs_wallet: 'signInSolana',
    insufficient_points: 'insufficientPoints',
    policy: 'policyError',
    bad_input: 'badInput',
    missing_fields: 'requiredFields',
    already_claimed: 'alreadyClaimed',
    not_done: 'taskNotDone',
    daily_cap: 'dailyCap',
    locked: 'accountLocked',
    bad_amount: 'badAmount',
    quote_failed: 'couldNotQuote',
    swap_disabled: 'inAppSwapUnavailable',
    sell_check_failed: 'sellCheckFailed',
  };
  const key = known[error.code];
  if (!key) return error.message || t(fallback);
  return t(key);
}

/** Case and task titles come from the database in English; known ids get a translation, others keep the API title. */
export function caseTitle(item: { id: string; title: string }, t: Translator) {
  const key = `caseTitle_${item.id}` as TranslationKey;
  return key in EN ? t(key) : item.title;
}

export function taskTitle(item: { id: string; title: string }, t: Translator) {
  const key = `task_${item.id}` as TranslationKey;
  return key in EN ? t(key) : item.title;
}
